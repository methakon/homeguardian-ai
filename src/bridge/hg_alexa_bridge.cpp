using json = nlohmann::json;
using namespace homeguardian;

namespace {

// Hard bounds for the local bridge. A single line larger than the contract's
// own request bound is rejected as malformed; we also guard the read here with
// a slightly larger line cap so a huge line cannot exhaust memory before the
// contract sees it.
constexpr size_t kMaxLineBytes = ALEXA_MAX_REQUEST_BYTES + 1024;
constexpr size_t kMaxRequests = 100000;  // defensive lifetime bound

// Map a contract error enum to a stable protocol error string. Generic only:
// no paths, tokens, or internal detail.
const char* error_code(AlexaError e) {
    switch (e) {
        case AlexaError::none: return "ok";
        case AlexaError::malformed: return "malformed";
        case AlexaError::unsupported_version: return "unsupported_version";
        case AlexaError::unauthorized: return "unauthorized";
        case AlexaError::forbidden: return "forbidden";
        case AlexaError::unavailable: return "unavailable";
    }
    return "error";
}

// A test-only credential verifier backed by a JSON file:
//   { "token": {"principal":"...", "allow_status":true,
//               "allow_alert_summary":true, "expires_at_ms": 0} }
// expires_at_ms == 0 means "never expires". No real secrets; generated by the
// test/demo. The token string is never logged or echoed.
class FileCredentialVerifier : public IAlexaCredentialVerifier {
public:
    struct Entry {
        std::string principal;
        bool allow_status = false;
        bool allow_alert_summary = false;
        std::chrono::system_clock::time_point expires_at{};
    };

    static FileCredentialVerifier load(const std::string& path) {
        FileCredentialVerifier v;
        std::ifstream f(path);
        if (!f.is_open()) {
            // No table => no credentials can verify. Fail closed: every verify
            // returns unauthenticated.
            return v;
        }
        json j;
        try {
            f >> j;
        } catch (const json::parse_error&) {
            return v;  // unreadable table => fail closed
        }
        for (auto it = j.begin(); it != j.end(); ++it) {
            Entry e;
            const json& val = it.value();
            if (val.contains("principal")) e.principal = val["principal"].get<std::string>();
            if (val.contains("allow_status")) e.allow_status = val["allow_status"].get<bool>();
            if (val.contains("allow_alert_summary"))
                e.allow_alert_summary = val["allow_alert_summary"].get<bool>();
            long long exp = val.value("expires_at_ms", 0LL);
            e.expires_at = exp == 0
                ? std::chrono::system_clock::time_point::max()
                : std::chrono::system_clock::time_point(std::chrono::milliseconds(exp));
            v.entries_[it.key()] = std::move(e);
        }
        return v;
    }

    AlexaAuthContext verify(const std::string& credential,
                            std::chrono::system_clock::time_point now) const override {
        AlexaAuthContext ctx;  // defaults: authenticated=false
        auto it = entries_.find(credential);
        if (it == entries_.end()) return ctx;      // unknown token: fail closed
        if (now >= it->second.expires_at) return ctx;  // expired: fail closed
        ctx.authenticated = true;
        ctx.principal = it->second.principal;
        ctx.allow_status = it->second.allow_status;
        ctx.allow_alert_summary = it->second.allow_alert_summary;
        return ctx;
    }

private:
    std::map<std::string, Entry> entries_;
};

// Status provider backed by the real Application + PersistenceAudit. Read-only
// snapshot. If persistence is unavailable, the app is reported unavailable
// (degraded) — matching the contract's fail-closed availability rule.
class AppStatusProvider : public IAlexaStatusProvider {
public:
    AppStatusProvider(Application& app, PersistenceAudit* audit, bool capture_enabled)
        : app_(app), audit_(audit), capture_enabled_(capture_enabled) {}

    AlexaStatusSnapshot snapshot() const override {
        AlexaStatusSnapshot s;
        // The bridge is a live local view of the real application. It does not
        // drive Application::run() (which blocks), so availability is based on
        // the REAL persistence health + the bridge being live, not on the
        // app's unstarted main-loop state. Capture reflects the REAL config
        // kill switch loaded at startup (fail-safe: false if config failed).
        s.state = "Running";
        s.capture_enabled = capture_enabled_;
        bool persistence_ok = (audit_ != nullptr) && audit_->healthy();
        s.available = persistence_ok;
        if (audit_) {
            // Aggregate alert summary from the real audit store. historical +
            // current alerts are both counted; ids are capped by the contract.
            std::vector<Alert> recent = audit_->alerts().find_recent(
                ALEXA_MAX_ALERTS_RETURNED);
            s.alert_count = audit_->total_alert_count();
            for (const auto& a : recent) s.alert_ids.push_back(a.alert_id);
            if (!recent.empty()) {
                // Highest severity among the most recent alerts
                // (info<warning<critical). Deterministic, non-sensitive.
                Severity top = Severity::info;
                for (const auto& a : recent) {
                    if (a.severity == Severity::critical) { top = Severity::critical; break; }
                    if (a.severity == Severity::warning) top = Severity::warning;
                }
                s.highest_severity = top == Severity::critical ? "critical"
                                     : top == Severity::warning ? "warning" : "info";
            }
        }
        return s;
    }

private:
    Application& app_;
    PersistenceAudit* audit_;
    bool capture_enabled_;
};

json response_to_json(const AlexaResponse& r) {
    json j;
    j["ok"] = r.ok;
    j["error"] = error_code(r.error);
    if (r.ok) {
        j["state"] = r.state;
        j["capture_enabled"] = r.capture_enabled;
        j["alert_count"] = r.alert_count;
        j["highest_severity"] = r.highest_severity;
        j["alert_ids"] = r.alert_ids;
    }
    return j;
}

}  // namespace

int main(int argc, char* argv[]) {
    // Usage: hg_alexa_bridge <config.json> <credentials.json>
    if (argc < 3) {
        std::cerr << "usage: hg_alexa_bridge <config.json> <credentials.json>\n";
        return 2;
    }
    const std::string config_path = argv[1];
    const std::string creds_path = argv[2];

    // Load the real configuration so the status view reflects the ACTUAL
    // capture kill-switch state (not just the RuntimeStatus default). A config
    // load failure is non-fatal for a read-only bridge: capture stays reported
    // as disabled (fail-safe) and the bridge keeps serving.
    bool capture_enabled = false;
    try {
        Config cfg;
        cfg.load(config_path);
        capture_enabled = cfg.media_capture_enabled;
    } catch (const std::exception&) {
        capture_enabled = false;  // fail-safe: never imply capture is on
    }

    // Start the real application lifecycle (simulator mode). Capture stays
    // disabled unless the config enables it; this bridge only READS state.
    // Application::run() blocks in the main loop, which we do not want here, so
    // the bridge builds a read-only status view over the REAL RuntimeStatus and
    // the REAL PersistenceAudit — the same components run() uses — without
    // duplicating any lifecycle logic.
    Application app;

    // Open persistence against a local audit DB. On failure the status
    // provider reports the app unavailable (degraded) — fail closed.
    PersistenceAudit* audit = nullptr;
    std::unique_ptr<PersistenceAudit> audit_owner;
    try {
        audit_owner = std::make_unique<PersistenceAudit>("homeguardian_bridge_audit.db");
        audit = audit_owner.get();
    } catch (const std::exception&) {
        audit = nullptr;  // degraded -> provider reports unavailable
    }

    FileCredentialVerifier verifier = FileCredentialVerifier::load(creds_path);
    AppStatusProvider provider(app, audit, capture_enabled);

    std::ios::sync_with_stdio(false);
    std::string line;
    size_t requests = 0;
    while (std::getline(std::cin, line)) {
        if (++requests > kMaxRequests) break;  // defensive lifetime bound
        // Trim a trailing CR (Windows-style) but do not otherwise mutate.
        if (!line.empty() && line.back() == '\r') line.pop_back();
        if (line.empty()) continue;

        // Control line for clean shutdown from the client.
        if (line == "shutdown") break;

        json out;
        if (line.size() > kMaxLineBytes) {
            out["ok"] = false;
            out["error"] = "malformed";
        } else {
            auto parsed = AlexaContract::parse(line);
            if (std::holds_alternative<AlexaError>(parsed)) {
                out["ok"] = false;
                out["error"] = error_code(std::get<AlexaError>(parsed));
            } else {
                AlexaResponse resp = AlexaContract::handle(
                    std::get<AlexaRequest>(parsed), verifier, provider);
                out = response_to_json(resp);
            }
        }
        std::cout << out.dump() << "\n";
        std::cout.flush();
    }
    return 0;
}
