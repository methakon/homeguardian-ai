int main(int argc, char* argv[]) {
    // Usage:
    //   hg_alexa_bridge <config.json> <credentials.json>
    //       NDJSON over stdin/stdout (existing contract path; used by tests).
    //   hg_alexa_bridge --http <config.json> <credentials.json>
    //                    [--port N] [--token-file PATH]
    //       Native loopback HTTP demo (serves the embedded dashboard + JSON API).
    bool http_mode = false;
    std::string uploads_dir;  // --uploads-dir: where the portal stores uploaded media
    // --camera-host names the authorized physical camera. When absent, NOTHING is assumed: the
    // camera routes 404 rather than reporting an invented device.
    std::string camera_host;
    uint16_t camera_port = 80;
    std::string camera_user = "admin";
    std::string camera_password;          // loaded from a 0600 file, NEVER from argv
    std::string camera_password_file;
    bool camera_allow_plaintext = false, camera_analysis = false;
    std::string camera_registry, camera_device_id, camera_credential_id;
    // Dynamic-address (DHCP) support for the physical camera. The MAC is the camera's identity,
    // never the address; scanning is opt-in (default off) and the state file is opt-in too.
    std::string camera_mac;
    std::string camera_scan_mode = "off";     // auto|off
    bool camera_scan = false;
    bool camera_scan_explicit = false;
    std::string camera_state_file;
    int base = 1;
    if (argc >= 2 && std::string(argv[1]) == "--http") {
        http_mode = true;
        base = 2;
    }
    if (argc < base + 2) {
        std::cerr << "usage: hg_alexa_bridge [--http] <config.json> <credentials.json>"
                     " [--port N] [--token-file PATH] [--secret-file PATH]"
                     " [--uploads-dir PATH]\n"
                     "  camera: --camera-host IP --camera-allow-plaintext"
                     " --camera-password-file PATH [--camera-port N] [--camera-user U]"
                     " [--camera-mac MAC] [--camera-scan auto|off] [--camera-state-file PATH]\n"
                     "  (--camera-scan auto re-finds the camera on its own /24 by MAC at most"
                     " once a minute on authorized requests, only while unavailable; no scheduler)\n"
                     "  (environment variables HG_HTTP_TOKEN, HG_HTTP_SECRET, HG_SECRET_FILE also supported)\n";
        return 2;
    }
    const std::string config_path = argv[base];
    const std::string creds_path = argv[base + 1];
    uint16_t http_port = 0;             // 0 = ephemeral
    std::string http_token = "demo-token";
    std::string http_secret = "";

    // Prefer safe environment variables or secret files to avoid command-line token exposure in ps
    const char* env_token = std::getenv("HG_HTTP_TOKEN");
    if (env_token && std::strlen(env_token) > 0) {
        http_token = env_token;
    }
    const char* env_secret = std::getenv("HG_HTTP_SECRET");
    if (env_secret && std::strlen(env_secret) > 0) {
        http_secret = env_secret;
    }
    const char* env_secret_file = std::getenv("HG_SECRET_FILE");
    if (env_secret_file && std::strlen(env_secret_file) > 0) {
        std::ifstream sf(env_secret_file);
        if (sf.is_open()) {
            std::getline(sf, http_secret);
        }
    }

    for (int i = base + 2; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "--port" && i + 1 < argc) {
            http_port = static_cast<uint16_t>(std::strtoul(argv[++i], nullptr, 10));
        } else if (a == "--token" && i + 1 < argc) {
            std::cerr << "SECURITY WARNING: passing --token on command line exposes credential in /proc and ps. Use --token-file or HG_HTTP_TOKEN instead.\n";
            http_token = argv[++i];
        } else if (a == "--camera-analysis") {
            camera_analysis = true;
        } else if (a == "--camera-registry" && i + 1 < argc) {
            camera_registry = argv[++i];
        } else if (a == "--camera-device-id" && i + 1 < argc) {
            camera_device_id = argv[++i];
        } else if (a == "--camera-credential-id" && i + 1 < argc) {
            camera_credential_id = argv[++i];
        } else if (a == "--camera-host" && i + 1 < argc) {
            camera_host = argv[++i];
        } else if (a == "--camera-port" && i + 1 < argc) {
            const std::string value = argv[++i];
            try {
                size_t end = 0;
                const auto number = std::stoul(value, &end);
                if (end != value.size() || number < 1 || number > 65535)
                    throw std::invalid_argument("port");
                camera_port = static_cast<uint16_t>(number);
            } catch (const std::exception&) {
                std::cerr << "camera configuration invalid\n";
                return 3;
            }
        } else if (a == "--camera-allow-plaintext") {
            camera_allow_plaintext = true;
        } else if (a == "--camera-user" && i + 1 < argc) {
            camera_user = argv[++i];
        } else if (a == "--camera-password-file" && i + 1 < argc) {
            // A FILE, never the command line: argv is visible to ps and lands in shell history.
            camera_password_file = argv[++i];
        } else if (a == "--camera-mac" && i + 1 < argc) {
            // The camera's MAC, so a DHCP move can be repaired without touching the address.
            camera_mac = argv[++i];
        } else if (a == "--camera-scan" && i + 1 < argc) {
            camera_scan_mode = argv[++i];
            camera_scan_explicit = true;
        } else if (a == "--camera-state-file" && i + 1 < argc) {
            camera_state_file = argv[++i];
        } else if (a == "--uploads-dir" && i + 1 < argc) {
            uploads_dir = argv[++i];
        } else if (a == "--token-file" && i + 1 < argc) {
            std::ifstream tf(argv[++i]);
            if (tf.is_open()) {
                std::getline(tf, http_token);
            }
        } else if (a == "--secret" && i + 1 < argc) {
            std::cerr << "SECURITY WARNING: passing --secret on command line exposes credential in /proc and ps. Use --secret-file or HG_HTTP_SECRET instead.\n";
            http_secret = argv[++i];
        } else if (a == "--secret-file" && i + 1 < argc) {
            std::ifstream sf(argv[++i]);
            if (sf.is_open()) {
                std::getline(sf, http_secret);
            }
        }
    }

    if (camera_analysis && (!http_mode || camera_host.empty() || camera_registry.empty() ||
        camera_device_id.empty() || camera_credential_id.empty())) {
        std::cerr << "camera analysis requires explicit source configuration\n"; return 3;
    }
    // Camera address discovery: validate the mode and the MAC BEFORE anything is built, and fail
    // closed on nonsense rather than treating an unparseable MAC as "match any device".
    if (camera_scan_mode != "auto" && camera_scan_mode != "off") {
        std::cerr << "camera scan mode invalid (auto|off)\n"; return 3;
    }
    // Supplying a MAC IS the operator's statement of device identity and of intent to survive a
    // DHCP move: the address is only "where it was last seen", the MAC is what the camera IS.
    // So enrolling a MAC arms the MAC-anchored rediscovery by default, and an IP change recovers
    // on the next failed fetch instead of leaving the feed DISCONNECTED forever. `--camera-scan
    // off` is still the explicit way to refuse it. Probes stay credential-free, MAC-matched,
    // bounded, and rate-limited to one rediscovery per minute by the locator.
    if (!camera_mac.empty() && !camera_scan_explicit) {
        camera_scan = true;                       // a MAC was enrolled: arm recovery
    } else {
        camera_scan = (camera_scan_mode == "auto");
    }
    if (!camera_mac.empty()) {
        homeguardian::camera::HardwareFingerprint fp;
        std::string why;
        if (!homeguardian::camera::HardwareFingerprint::normalize(camera_mac, &fp, &why)) {
            std::cerr << "camera MAC invalid: " << why << "\n"; return 3;
        }
        camera_mac = fp.canonical();
    }
    if (camera_scan && (camera_mac.empty() || !camera_analysis)) {
        std::cerr << "camera scan requires explicit --camera-mac and registry-backed --camera-analysis\n"; return 3;
    }
    if (camera_scan && camera_host.empty()) {
        std::cerr << "camera scan requires --camera-host (the /24 is derived from it)\n"; return 3;
    }
    if (!camera_state_file.empty() && camera_state_file.front() != '/') {
        std::cerr << "camera state file must be an absolute path\n"; return 3;
    }
    if (!camera_state_file.empty() && !http_mode) {
        std::cerr << "camera state file is only used in --http mode\n"; return 3;
    }
    // Never silently discard the configured camera credential or opt into
    // plaintext merely because a host was supplied. Read the exact opened file
    // with owner-only permissions, no symlink following and a hard size cap.
    if (!camera_host.empty()) {
        if (!camera_allow_plaintext || camera_password_file.empty()) {
            std::cerr << "camera requires explicit plaintext opt-in and credential file\n";
            return 3;
        }
        const int fd = ::open(camera_password_file.c_str(), O_RDONLY | O_NOFOLLOW | O_CLOEXEC);
        struct stat st {};
        std::string value(1025, '\0');
        ssize_t count = -1;
        if (fd >= 0) {
            if (::fstat(fd, &st) == 0 && S_ISREG(st.st_mode) &&
                st.st_uid == ::geteuid() && (st.st_mode & 077) == 0)
                count = ::read(fd, value.data(), value.size());
            ::close(fd);
        }
        if (count <= 0 || count > 1024) {
            std::cerr << "camera credential file unavailable or insecure\n";
            return 3;
        }
        value.resize(static_cast<size_t>(count));
        if (!value.empty() && value.back() == '\n') value.pop_back();
        if (!value.empty() && value.back() == '\r') value.pop_back();
        if (value.empty() || value.find_first_of("\r\n") != std::string::npos ||
            value.find('\0') != std::string::npos) {
            std::cerr << "camera credential file invalid\n";
            return 3;
        }
        camera_password = std::move(value);
    }

    // Initialize logging. The Logger writes to stdout, which would interleave
    // with the NDJSON protocol on stdout — so set the level to "critical": the
    // only message that could appear is a fatal one, and normal operation
    // emits nothing to stdout. Alerts are still recorded durably and reported
    // in the scenario JSON summary. The file sink still captures detail in
    // homeguardian.log for debugging.
    Logger::initialize("critical");

    // Load the real configuration so the status view reflects the ACTUAL
    // capture kill-switch state (not just the RuntimeStatus default). A config
    // load failure is non-fatal for a read-only bridge: capture stays reported
    // as disabled (fail-safe) and the bridge keeps serving.
    bool capture_enabled = false;
    int alert_retention_days = Config{}.alert_retention_days;  // safe default (30)
    try {
        Config cfg;
        cfg.load(config_path);
        capture_enabled = cfg.media_capture_enabled;
        alert_retention_days = cfg.alert_retention_days;
    } catch (const std::exception&) {
        capture_enabled = false;  // fail-safe: never imply capture is on
    }

    // Start the real application lifecycle (simulator mode). Capture stays
    // disabled unless the config enables it; this bridge only READS state.
    // Application::run() blocks in the main loop, which we do not want here, so
    // the bridge builds a read-only status view over the REAL RuntimeStatus and
    // the REAL PersistenceAudit — the same components run() uses — without
    // duplicating any lifecycle logic.
    Application app;
    // Reflect the real config kill-switch into RuntimeStatus so the status view
    // and the scenario runner both see the ACTUAL capture state.
    app.get_status().capture_enabled.store(capture_enabled);

    // Open persistence against a local audit DB. On failure the status
    // provider reports the app unavailable (degraded) — fail closed.
    PersistenceAudit* audit = nullptr;
    std::unique_ptr<PersistenceAudit> audit_owner;
    try {
        audit_owner = std::make_unique<PersistenceAudit>(std::getenv("HG_BRIDGE_AUDIT_DB") ? std::getenv("HG_BRIDGE_AUDIT_DB") : "homeguardian_bridge_audit.db");
        audit = audit_owner.get();
    } catch (const std::exception&) {
        audit = nullptr;  // degraded -> provider reports unavailable
    }
    // Credential verification. Two modes, chosen explicitly — never silently:
    //  - HG_BRIDGE_SECURE_CREDS=1: use AlexaCredentialStore, which enforces a
    //    0600 owner-only credential file and fails closed on any problem. This
    //    is the production-style path. A load failure leaves every verify
    //    unauthenticated (no permissive fallback).
    //  - default: the local FileCredentialVerifier (no file-permission
    //    enforcement) for development/tests where the fixture is not 0600.
    // Both use the same JSON schema; neither logs or returns secret values.
    std::unique_ptr<IAlexaCredentialVerifier> verifier;
    try {
        if (std::getenv("HG_BRIDGE_SECURE_CREDS") != nullptr) {
            auto store = std::make_unique<AlexaCredentialStore>();
            auto load_res = store->load(creds_path);
            if (!load_res.ok) {
                // Fail closed: refuse to serve with an insecurely provisioned or
                // unreadable credential store. Do NOT fall back to the permissive
                // local verifier. The generic reason carries no secret or path.
                std::cerr << "credential store failed to load securely: "
                          << load_res.reason << "\n";
                return 3;
            }
            verifier = std::move(store);
        } else {
            verifier = std::make_unique<FileCredentialVerifier>(
                FileCredentialVerifier::load(creds_path));
        }
    } catch (const std::exception&) {
        // A malformed or unreadable credential table must fail CLOSED and CLEANLY.
        // Previously an unhandled parse exception escaped main() and aborted the
        // process (SIGABRT, core dump) before a single request was served - the
        // same class of defect as the v21 logger abort. The message is generic on
        // purpose: it must not echo the path or any file content, and there is no
        // permissive fallback and no unauthenticated serving.
        std::cerr << "credential load failed (fail-closed, no fallback): "
                     "malformed or unreadable credential table\n";
        return 3;
    }
    AppStatusProvider provider(app, audit, capture_enabled);

    // Native HTTP demo mode: serve the loopback dashboard + JSON API and return
    // when shutdown is requested. Otherwise fall through to the NDJSON loop.
    if (http_mode) {
        return run_http_mode(app, audit, *verifier, provider, http_token, http_port,
                             alert_retention_days, http_secret, uploads_dir,
                             camera_host, camera_port, camera_user, camera_password,
                             camera_analysis, camera_registry, camera_device_id, camera_credential_id,
                             camera_mac, camera_scan, camera_state_file);
    }

    std::ios::sync_with_stdio(false);
    std::string line;
    size_t requests = 0;
    while (std::getline(std::cin, line)) {
        if (++requests > kMaxRequests) break;  // defensive lifetime bound
        // Trim a trailing CR (Windows-style) but do not otherwise mutate.
        if (!line.empty() && line.back() == '\r') line.pop_back();
        if (line.empty()) continue;

        // Structured local-stdio simulation controls. Like run_scenario below,
        // these are never part of the authenticated read-only MCP/HTTP surface.
        // The review gateway runs this process in a fresh synthetic fixture.
        if (line.size() <= kMaxLineBytes && line.front() == '{') {
            const auto control = json::parse(line, nullptr, false);
            if (control.is_object() && control.contains("op") && control["op"].is_string()) {
                const auto op = control["op"].get<std::string>();
                if (op == "scenarios" || op == "scenario") {
                    json result;
                    if (op == "scenarios" && control.size() == 1) {
                        result = scenarios_payload();
                    } else if (op == "scenario" && control.size() == 2 &&
                               control.contains("id") && control["id"].is_string()) {
                        const auto id = control["id"].get<std::string>();
                        const auto* spec = find_demo_scenario(id);
                        if (spec) result = scenario_result_json(app, audit, *spec, false, 0);
                        else result = {{"ok", false}, {"error", "unknown_scenario"}};
                    } else {
                        result = {{"ok", false}, {"error", "invalid_simulation_request"}};
                    }
                    std::cout << result.dump() << "\n";
                    std::cout.flush();
                    continue;
                }
            }
        }

        // Control line for clean shutdown from the client.
        if (line == "shutdown") break;

        // Control line: run the real synthetic household scenario. Format:
        //   run_scenario [cycles]
        // Reuses the real Application pipeline; persists alerts; returns a
        // real summary. Never activates a physical sensor.
        // Control line: run a real synthetic scenario.
        // Format: run_scenario [cycles] [scenario_id]
        // Reuses the real Application pipeline; persists the REAL delivered
        // alerts; returns a real summary. Never activates a physical sensor.
        if (line.rfind("run_scenario", 0) == 0) {
            int cycles = 5;
            bool cycles_set = false;
            std::string sid;
            std::istringstream iss(line);
            std::string cmd;
            iss >> cmd;
            if (iss >> cycles) cycles_set = true;
            if (iss >> sid) { /* optional scenario id */ }
            if (cycles < 0) cycles = 0;
            if (cycles > 100) cycles = 100;  // bound
            const DemoScenario* spec = sid.empty()
                ? find_demo_scenario(default_demo_scenario_id())
                : find_demo_scenario(sid);
            json sout;
            if (spec == nullptr) {
                sout["ok"] = false;
                sout["error"] = "unknown_scenario";
                sout["scenario_id"] = sid;
            } else {
                sout = scenario_result_json(app, audit, *spec, cycles_set,
                                            static_cast<unsigned>(cycles));
            }
            std::cout << sout.dump() << "\n";
            std::cout.flush();
            continue;
        }

        json out;
        if (line.size() > kMaxLineBytes) {
            out["ok"] = false;
            out["error"] = "malformed";
        } else {
            auto parsed = AlexaContract::parse(line);
            if (std::holds_alternative<AlexaError>(parsed)) {
                out["ok"] = false;
                out["error"] = error_code(std::get<AlexaError>(parsed));
            } else {
                AlexaResponse resp = AlexaContract::handle(
                    std::get<AlexaRequest>(parsed), *verifier, provider);
                out = response_to_json(resp);
            }
        }
        std::cout << out.dump() << "\n";
        std::cout.flush();
    }
    return 0;
}
