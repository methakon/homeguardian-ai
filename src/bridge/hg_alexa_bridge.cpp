// hg_alexa_bridge: a small LOCAL-ONLY executable that exposes the real C++
// AlexaContract over a newline-delimited JSON (NDJSON) stdio boundary. It is the
// process boundary the JavaScript Alexa adapter talks to — NOT a mock.
//
// Design constraints (F22-30):
//  - No network listener. stdin/stdout only. Nothing binds a port.
//  - Newline-delimited JSON: one request object per line in, one response
//    object per line out. Bounded request size; oversized lines are rejected.
//  - The request is parsed and handled by the REAL AlexaContract (parse +
//    handle), so all validation, version gating, and fail-closed auth live in
//    the shared contract — not duplicated here.
//  - Authentication uses a test-only verifier loaded from an env-var-free,
//    file-based credential table whose path is passed on the command line. No
//    real secrets; the table is generated by the test/demo, kept out of version
//    control. The credential value is NEVER logged or echoed.
//  - Read-only: the bridge only serves `status` and `alert_summary`. It cannot
//    enable capture, grant consent, change config, or activate a sensor.
//  - Status/alert data come from the REAL Application lifecycle +
//    RuntimeStatus + PersistenceAudit (temporary DB), so the JS client sees the
//    same state the running app reports.
//  - Bounded lifetime: the bridge exits on EOF, on a "shutdown" control line,
//    or after a max number of requests (defensive bound). No orphan processes.

