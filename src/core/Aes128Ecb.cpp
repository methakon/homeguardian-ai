bool Aes128Ecb::encrypt_block(const std::string& key, uint8_t* block) {
    if (!valid_key(key) || block == nullptr) return false;
    uint8_t round_key[kExpandedKeyBytes];
    expand_key(key, round_key);
    add_round_key(block, round_key, 0);
    for (size_t round = 1; round < kNr; ++round) {
        sub_bytes(block);
        shift_rows(block);
        mix_columns(block);
        add_round_key(block, round_key, round);
    }
    sub_bytes(block);
    shift_rows(block);
    add_round_key(block, round_key, kNr);
    return true;
}

bool Aes128Ecb::decrypt_block(const std::string& key, uint8_t* block) {
    if (!valid_key(key) || block == nullptr) return false;
    uint8_t round_key[kExpandedKeyBytes];
    expand_key(key, round_key);
    add_round_key(block, round_key, kNr);
    for (size_t round = kNr - 1; round > 0; --round) {
        inv_shift_rows(block);
        inv_sub_bytes(block);
        add_round_key(block, round_key, round);
        inv_mix_columns(block);
    }
    inv_shift_rows(block);
    inv_sub_bytes(block);
    add_round_key(block, round_key, 0);
    return true;
}

bool Aes128Ecb::encrypt_ecb(const std::string& key, uint8_t* data, size_t size, std::string* why) {
    if (why != nullptr) why->clear();
    if (!valid_key(key)) {
        if (why != nullptr) *why = "AES-128 key must be exactly 16 bytes";
        return false;
    }
    if (data == nullptr || size == 0 || size % kBlockBytes != 0) {
        if (why != nullptr) *why = "AES-ECB input must be a non-zero multiple of 16 bytes";
        return false;
    }
    for (size_t offset = 0; offset < size; offset += kBlockBytes) {
        if (!encrypt_block(key, data + offset)) return false;
    }
    return true;
}

bool Aes128Ecb::decrypt_ecb(const std::string& key, uint8_t* data, size_t size, std::string* why) {
    if (why != nullptr) why->clear();
    if (!valid_key(key)) {
        if (why != nullptr) *why = "AES-128 key must be exactly 16 bytes";
        return false;
    }
    if (data == nullptr || size == 0 || size % kBlockBytes != 0) {
        if (why != nullptr) *why = "AES-ECB input must be a non-zero multiple of 16 bytes";
        return false;
    }
    for (size_t offset = 0; offset < size; offset += kBlockBytes) {
        if (!decrypt_block(key, data + offset)) return false;
    }
    return true;
}

