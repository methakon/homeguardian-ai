const uint8_t kRcon[11] = {0x8d, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36};

uint8_t xtime(uint8_t x) { return static_cast<uint8_t>((x << 1) ^ (((x >> 7) & 1) * 0x1b)); }

uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    for (int i = 0; i < 8; ++i) {
        if ((b & 1) != 0) p ^= a;
        const uint8_t hi = static_cast<uint8_t>(a & 0x80);
        a = static_cast<uint8_t>(a << 1);
        if (hi != 0) a ^= 0x1b;
        b = static_cast<uint8_t>(b >> 1);
    }
    return p;
}

void expand_key(const std::string& key, uint8_t* round_key) {
    for (size_t i = 0; i < kNk * 4; ++i) round_key[i] = static_cast<uint8_t>(key[i]);
    uint8_t t[4];
    for (size_t i = kNk; i < (kNr + 1) * kNk; ++i) {
        for (size_t j = 0; j < 4; ++j) t[j] = round_key[(i - 1) * 4 + j];
        if (i % kNk == 0) {
            const uint8_t first = t[0];
            t[0] = static_cast<uint8_t>(kSbox[t[1]] ^ kRcon[i / kNk]);
            t[1] = kSbox[t[2]];
            t[2] = kSbox[t[3]];
            t[3] = kSbox[first];
        }
        for (size_t j = 0; j < 4; ++j) {
            round_key[i * 4 + j] = static_cast<uint8_t>(round_key[(i - kNk) * 4 + j] ^ t[j]);
        }
    }
}

void add_round_key(uint8_t* state, const uint8_t* round_key, size_t round) {
    for (size_t i = 0; i < 16; ++i) state[i] ^= round_key[round * 16 + i];
}
void sub_bytes(uint8_t* state) {
    for (size_t i = 0; i < 16; ++i) state[i] = kSbox[state[i]];
}
void inv_sub_bytes(uint8_t* state) {
    for (size_t i = 0; i < 16; ++i) state[i] = kRsbox[state[i]];
}
void shift_rows(uint8_t* s) {
    uint8_t t;
    t = s[1];  s[1] = s[5];  s[5] = s[9];   s[9] = s[13];  s[13] = t;
    // Row 2 rotates by two, which is its own inverse: two swaps, not a 4-cycle. Writing it as a cycle
    // shifted the row by one instead of two and produced ciphertext that was wrong everywhere downstream.
    t = s[2];  s[2] = s[10]; s[10] = t;
    t = s[6];  s[6] = s[14]; s[14] = t;
    t = s[3];  s[3] = s[15]; s[15] = s[11]; s[11] = s[7];  s[7] = t;
}
void inv_shift_rows(uint8_t* s) {
    uint8_t t;
    t = s[13]; s[13] = s[9];  s[9] = s[5];   s[5] = s[1];   s[1] = t;
    t = s[6];  s[6] = s[14];  s[14] = t;
    t = s[2];  s[2] = s[10];  s[10] = t;
    t = s[7];  s[7] = s[11];  s[11] = s[15]; s[15] = s[3];  s[3] = t;
}
void mix_columns(uint8_t* s) {
    for (size_t c = 0; c < 4; ++c) {
        const uint8_t col = static_cast<uint8_t>(s[c * 4 + 0] ^ s[c * 4 + 1] ^ s[c * 4 + 2] ^ s[c * 4 + 3]);
        const uint8_t t0 = s[c * 4 + 0];
        const uint8_t a = xtime(static_cast<uint8_t>(s[c * 4 + 0] ^ s[c * 4 + 1]));
        const uint8_t b = xtime(static_cast<uint8_t>(s[c * 4 + 1] ^ s[c * 4 + 2]));
        const uint8_t d = xtime(static_cast<uint8_t>(s[c * 4 + 2] ^ s[c * 4 + 3]));
        const uint8_t e = xtime(static_cast<uint8_t>(s[c * 4 + 3] ^ t0));
        s[c * 4 + 0] = static_cast<uint8_t>(s[c * 4 + 0] ^ a ^ col);
        s[c * 4 + 1] = static_cast<uint8_t>(s[c * 4 + 1] ^ b ^ col);
        s[c * 4 + 2] = static_cast<uint8_t>(s[c * 4 + 2] ^ d ^ col);
        s[c * 4 + 3] = static_cast<uint8_t>(s[c * 4 + 3] ^ e ^ col);
    }
}
void inv_mix_columns(uint8_t* s) {
    for (size_t c = 0; c < 4; ++c) {
        const uint8_t a = s[c * 4 + 0], b = s[c * 4 + 1], d = s[c * 4 + 2], e = s[c * 4 + 3];
        s[c * 4 + 0] = static_cast<uint8_t>(gmul(a, 0x0e) ^ gmul(b, 0x0b) ^ gmul(d, 0x0d) ^ gmul(e, 0x09));
        s[c * 4 + 1] = static_cast<uint8_t>(gmul(a, 0x09) ^ gmul(b, 0x0e) ^ gmul(d, 0x0b) ^ gmul(e, 0x0d));
        s[c * 4 + 2] = static_cast<uint8_t>(gmul(a, 0x0d) ^ gmul(b, 0x09) ^ gmul(d, 0x0e) ^ gmul(e, 0x0b));
        s[c * 4 + 3] = static_cast<uint8_t>(gmul(a, 0x0b) ^ gmul(b, 0x0d) ^ gmul(d, 0x09) ^ gmul(e, 0x0e));
    }
}

