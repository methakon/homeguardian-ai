#!/usr/bin/env python3
"""HG-LAN-MTLS-07 - network failure recovery against REAL sockets, not a simulated policy.

test_reconnect.py is a deterministic simulation of the reconnect *policy*. This suite drives actual
TLS over loopback and injects real faults, because a policy that is correct in the abstract can still
be wrong when a socket half-dies, a segment is lost, or a peer resets the connection.

Faults injected (all real, no mocks):
  1  clean control                    - a benign session must connect and deliver exactly once
  2  connection refused, then up      - refusal is not CONNECTED; recovery after the peer returns
  3  abort mid-handshake              - TCP accepted, TLS never completes
  4  server accepts but never ACKs    - a completed handshake is NOT authentication; must time out
  5  delivered then RST before ACK    - the ACK is lost: the retry MUST be de-duplicated
                                        (at-least-once send + idempotent dedup = exactly-once)

Invariants asserted: a lost/unconfirmed link NEVER reports CONNECTED; waits are bounded; a retry
after a lost ACK delivers exactly once; retries do not multiply deliveries.

Fixture layout (dev-only, generated by scripts/mtls_fixtures/generate_dev_fixtures.sh):
  <D>/dev-ca/ca.crt                  the dev CA the endpoint trusts
  <D>/runtime/server-good-SAN.crt    hub certificate, SAN includes 127.0.0.1
  <D>/devices/mi-a3-01.crt|.key      a device certificate (identity = fingerprint, never CN)
"""
from __future__ import annotations

import os
import socket
import ssl
import struct
import sys
import threading
import time

D = os.environ.get("HG_MTLS_FIXTURES", os.path.expanduser("~/.hermes/cache/scratch/hg-mtls-07-fixtures"))
CA = f"{D}/dev-ca/ca.crt"
SRV, SRV_KEY = f"{D}/runtime/server-good-SAN.crt", f"{D}/runtime/server-good-SAN.key"
CLI, CLI_KEY = f"{D}/devices/mi-a3-01.crt", f"{D}/devices/mi-a3-01.key"
HOST, TIMEOUT = "127.0.0.1", 3.0
MSG = "msg-0001"                      # one logical message, resent after a lost ACK


def missing():
    return [p for p in (CA, SRV, SRV_KEY, CLI, CLI_KEY) if not os.path.exists(p)]


def server_ctx():
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    ctx.minimum_version = ssl.TLSVersion.TLSv1_2
    ctx.verify_mode = ssl.CERT_REQUIRED
    ctx.load_verify_locations(CA)
    ctx.load_cert_chain(SRV, SRV_KEY)
    return ctx


def client_ctx():
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    ctx.minimum_version = ssl.TLSVersion.TLSv1_2
    ctx.verify_mode = ssl.CERT_REQUIRED
    ctx.check_hostname = True
    ctx.load_verify_locations(CA)
    ctx.load_cert_chain(CLI, CLI_KEY)
    return ctx


def rst(tls):
    """Close with SO_LINGER(1,0): the peer sees an abrupt reset, not a clean FIN."""
    try:
        tls.setsockopt(socket.SOL_SOCKET, socket.SO_LINGER, struct.pack("ii", 1, 0))
    except OSError:
        pass
    tls.close()


def serve(listener, mode, journal):
    """One connection. `journal` records what the endpoint did, not what the client claims."""
    try:
        conn, _ = listener.accept()
    except OSError:
        return
    if mode == "mid_handshake_abort":
        conn.close()                                   # TCP accepted, TLS abandoned
        return
    try:
        tls = server_ctx().wrap_socket(conn, server_side=True)
    except (ssl.SSLError, OSError):
        conn.close()
        return
    try:
        if mode == "silent":
            tls.recv(64)
            time.sleep(TIMEOUT + 2)                    # handshake done, application never answers
            return
        data = tls.recv(4096).decode(errors="replace")
        if not data:
            return
        mid = data.split(":", 1)[0]
        if mode == "deliver_then_die":
            # the endpoint DID accept the message, but the ACK never reaches the client
            if mid in journal["seen"]:
                journal["dupes"] += 1
            else:
                journal["seen"].add(mid)
                journal["delivered"] += 1
            rst(tls)
            return
        if mid in journal["seen"]:
            journal["dupes"] += 1
        else:
            journal["seen"].add(mid)
            journal["delivered"] += 1
        tls.sendall(b"OK")                             # the gate: an application-level ACK
        if mode == "rst_after_ack":
            # let the ACK reach the client first, so this case tests the reset that FOLLOWS a
            # confirmed session. Without the pause the RST races the ACK, the ACK is discarded,
            # and the case becomes a coin flip - a flaky assertion, not a property.
            time.sleep(0.25)
            rst(tls)
            return
        tls.close()
    except (ssl.SSLError, OSError):
        try:
            conn.close()
        except OSError:
            pass


def listen():
    lst = socket.socket()
    lst.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    lst.bind((HOST, 0))
    lst.listen(1)
    return lst


def start(mode, journal):
    lst = listen()
    threading.Thread(target=serve, args=(lst, mode, journal), daemon=True).start()
    return lst, lst.getsockname()[1]


def session(port, timeout=TIMEOUT):
    """Client half. Returns (connected, detail). CONNECTED requires the application ACK."""
    try:
        with socket.create_connection((HOST, port), timeout=timeout) as sock:
            with client_ctx().wrap_socket(sock, server_hostname=HOST) as tls:
                tls.settimeout(timeout)
                tls.sendall(f"{MSG}:payload".encode())
                ack = tls.recv(2)
                if ack != b"OK":
                    return False, f"no ack ({ack!r})"
                return True, "connected"
    except (ssl.SSLError, socket.timeout, TimeoutError) as exc:
        return False, type(exc).__name__
    except OSError as exc:
        return False, type(exc).__name__


def case_no_ack_then_retry():
    """Fault 5: message reached the endpoint, ACK was lost. The retry must dedupe."""
    j = {"seen": set(), "delivered": 0, "dupes": 0}
    lst, port = start("deliver_then_die", j)
    c1, d1 = session(port)                              # no ACK -> must NOT be CONNECTED
    lst.close()
    lst2, port2 = start("deliver_then_die", j)
    time.sleep(0.05)
    c2, d2 = session(port2)                             # resend the SAME message id
    lst2.close()
    ok = (not c1) and (not c2) and j["delivered"] == 1 and j["dupes"] == 1
    return ok, f"first={c1}({d1}) retry={c2}({d2}) delivered={j['delivered']} dupes={j['dupes']}"


def case_refused_then_recovers():
    lst = listen()
    port = lst.getsockname()[1]
    lst.close()                                         # nothing listening -> refusal
    time.sleep(0.05)
    c1, d1 = session(port, timeout=2.0)
    j = {"seen": set(), "delivered": 0, "dupes": 0}
    lst2, port2 = start("clean", j)
    time.sleep(0.05)
    c2, d2 = session(port2)
    lst2.close()
    ok = (not c1) and c2 and j["delivered"] == 1
    return ok, f"refused={c1}({d1}) after_recovery={c2}({d2}) delivered={j['delivered']}"


def case_mid_handshake_abort():
    j = {"seen": set(), "delivered": 0, "dupes": 0}
    lst, port = start("mid_handshake_abort", j)
    time.sleep(0.05)
    c, d = session(port, timeout=2.0)
    lst.close()
    return (not c), f"connected={c} detail={d} (a TCP accept is not a session)"


def case_silent_never_acks():
    j = {"seen": set(), "delivered": 0, "dupes": 0}
    lst, port = start("silent", j)
    time.sleep(0.05)
    t0 = time.time()
    c, d = session(port)
    elapsed = time.time() - t0
    lst.close()
    ok = (not c) and elapsed < TIMEOUT + 1.5
    return ok, f"connected={c} detail={d} elapsed={elapsed:.2f}s (bounded, < {TIMEOUT + 1.5:.1f}s)"


def case_control_and_rst():
    j = {"seen": set(), "delivered": 0, "dupes": 0}
    lst, port = start("clean", j)
    time.sleep(0.05)
    c1, d1 = session(port)
    lst.close()
    j2 = {"seen": set(), "delivered": 0, "dupes": 0}
    lst2, port2 = start("rst_after_ack", j2)
    time.sleep(0.05)
    c2, d2 = session(port2)
    # the RST lands after the ACK, so this session legitimately connected first
    lst2.close()
    ok = c1 and c2 and j["delivered"] == 1
    return ok, f"control={c1}({d1}) rst_after_ack={c2}({d2})"

def case_rst_is_detected():
    """An abrupt reset must surface as a fault, never as a healthy link."""
    j = {"seen": set(), "delivered": 0, "dupes": 0}
    lst, port = start("clean", j)
    time.sleep(0.05)
    fault = None
    try:
        with socket.create_connection((HOST, port), timeout=TIMEOUT) as sock:
            with client_ctx().wrap_socket(sock, server_hostname=HOST) as tls:
                tls.settimeout(TIMEOUT)
                tls.sendall(f"{MSG}:payload".encode())
                tls.recv(2)
                time.sleep(0.1)
                try:
                    tls.sendall(b"after-the-peer-closed")
                    tls.settimeout(1.5)
                    got = tls.recv(2)
                    if got == b"":
                        fault = "clean EOF (link down)"
                except OSError as exc:
                    fault = type(exc).__name__
    except OSError as exc:
        fault = type(exc).__name__
    lst.close()
    return bool(fault), f"fault detected as: {fault}"


def main():
    if missing():
        print("fixtures missing: " + ", ".join(missing()))
        print("generate them first:  scripts/mtls_fixtures/generate_dev_fixtures.sh")
        return 2
    cases = [
        ("1 clean control + rst_after_ack", case_control_and_rst),
        ("2 refused, then peer returns", case_refused_then_recovers),
        ("3 abort mid-handshake", case_mid_handshake_abort),
        ("4 silent peer, no ACK", case_silent_never_acks),
        ("5 delivered then lost ACK -> retry deduped", case_no_ack_then_retry),
        ("6 abrupt reset is detected as a fault", case_rst_is_detected),
    ]
    failed = 0
    for name, fn in cases:
        try:
            ok, detail = fn()
        except Exception as exc:                       # noqa: BLE001
            ok, detail = False, f"{type(exc).__name__}: {exc}"
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}: {detail}")
        failed += 0 if ok else 1
    print(f"  {len(cases) - failed}/{len(cases)} properties hold")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
