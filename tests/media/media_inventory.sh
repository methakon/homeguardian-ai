#!/usr/bin/env bash
# media_manage.sh — the shared media storage tool. Never deletes anything: disposal is the owner's call,
# because silent deletion of evidence is indistinguishable from losing it.
#
#   inventory                     sizes, counts, limits and anything past its retention deadline
#   checksum FILE WORKER CASE DEVICE CLASS   SHA-256 + a metadata record with the deadline filled in
#   expire                        list expired artifacts (does NOT delete them)
set -uo pipefail
MEDIA="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WARN=$((2*1024*1024*1024)); STOP=$((5*1024*1024*1024))

usage() { sed -n '2,9p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

human() { numfmt --to=iec --suffix=B "$1" 2>/dev/null || echo "${1}B"; }

cmd_inventory() {
  echo "media tree: $MEDIA"
  local total=0
  for class in images/real video/real audio/real images/synthetic video/synthetic audio/synthetic quarantine metadata/records; do
    local dir="$MEDIA/$class"
    [[ -d "$dir" ]] || continue
    local bytes files
    bytes=$(du -sb "$dir" 2>/dev/null | cut -f1); files=$(find "$dir" -type f 2>/dev/null | wc -l)
    total=$((total + bytes))
    printf '  %-22s %6s files  %10s\n' "$class" "$files" "$(human "$bytes")"
  done
  echo "  TOTAL                  $(human "$total")   (warn at $(human $WARN), stop new real capture at $(human $STOP))"
  if (( total >= STOP )); then echo "  LIMIT: at or above the stop threshold — no new real capture until reviewed";
  elif (( total >= WARN )); then echo "  LIMIT: above the warning threshold"; fi
  echo; echo "past retention deadline:"
  cmd_expire | sed 's/^/  /'
}

cmd_checksum() {
  local file="$1" worker="$2" case_id="$3" device="$4" class="$5"
  [[ -f "$file" ]] || { echo "no such file: $file" >&2; return 2; }
  local sha; sha=$(sha256sum "$file" | cut -d' ' -f1)
  local deadline; deadline=$(date -u -d '+30 days' '+%Y-%m-%dT%H:%M:%SZ')
  [[ "$class" == "SYNTHETIC" ]] && deadline=$(date -u -d '+365 days' '+%Y-%m-%dT%H:%M:%SZ')
  local name; name="$(basename "$file")"
  local record="$MEDIA/metadata/records/${name%.*}.json"
  cat > "$record" <<JSON
{
  "capture_utc": "$(date -u -r "$file" '+%Y-%m-%dT%H:%M:%SZ')",
  "worker": "$worker",
  "test_case": "$case_id",
  "device_identity": "$device",
  "acquisition_method": "to-be-recorded-by-the-capturing-worker",
  "media_type": "$(case "$name" in *.png|*.jpg|*.jpeg) echo image;; *.mp4|*.mkv|*.avi|*.webm) echo video;; *) echo audio;; esac)",
  "encoding": "${name##*.}",
  "sha256": "$sha",
  "classification": "$class",
  "consent_status": "granted",
  "authorization_reference": "owner directive: shared media storage policy",
  "processing_results": {},
  "retention_deadline_utc": "$deadline",
  "disposal_status": "retained",
  "notes": "generated by media_manage.sh checksum"
}
JSON
  chmod 600 "$record"
  echo "sha256: $sha"
  echo "record: $record"
}

cmd_expire() {
  local now; now=$(date +%s)
  find "$MEDIA/metadata/records" -name '*.json' 2>/dev/null | while read -r rec; do
    local dl; dl=$(grep -o '"retention_deadline_utc": *"[^"]*"' "$rec" | sed 's/.*"\([0-9TZ:.-]*\)"/\1/')
    [[ -z "$dl" ]] && continue
    local epoch; epoch=$(date -d "$dl" +%s 2>/dev/null) || continue
    (( epoch < now )) && echo "EXPIRED $(basename "$rec") (deadline $dl)"
  done
}

case "${1:-}" in
  inventory) cmd_inventory ;;
  checksum) shift; cmd_checksum "$@" ;;
  expire) cmd_expire ;;
  *) usage; exit 1 ;;
esac
