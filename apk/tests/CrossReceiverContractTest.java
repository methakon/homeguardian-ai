package org.homeguardian.harness;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.List;

/**
 * CrossReceiverContractTest - producer -> transport -> receiver-contract fixtures.
 *
 * WHY THIS EXISTS
 * The Android transport decides RETRY / PERMANENT / SUSPEND from the hub's refusal reason, and that
 * decision is what stops a phone from pushing observations to a hub that has already refused it. The
 * decision is only correct if the Android token set matches what the receiver actually emits. When
 * they drift the failure is silent and one-directional: an unrecognised reason falls through to
 * PERMANENT, so a condition that should SUSPEND the transport instead drops a single observation and
 * the phone keeps trying.
 *
 * The fixture is generated by scripts/gen_cross_receiver_fixture.py FROM THE C++ SOURCE
 * (reject_reason_to_string in src/net/DeviceProtocol.cpp), not from a hand-copied list - a copied
 * list would agree with whatever Android already believes and prove nothing.
 *
 * WHAT THIS ASSERTS
 *   X1  the Android sets and the receiver's emitted tokens are the same vocabulary
 *   X2  the fixture's own classification of every token matches this class's classifyReason()
 *       (so the Python mirror and the Java production code cannot disagree silently)
 *   X3  consent withdrawal and device revocation SUSPEND, and a suspended transport does not retry
 *   X4  a revoked/unpaired/unknown device STOPPED, rather than retried to the bound
 *   X5  an unknown reason fails closed to PERMANENT
 *   X6  replay is not retried
 *   X7  schema_version rules, including 0 (present but not 1 => refused, NOT treated as absent)
 *   X8  provenance may never be elevated, and fixture data is never labelled real evidence
 *   X9  negative controls: the assertions above can fail
 *
 * Opens no socket, installs nothing, activates no sensor. Pure decision logic plus one fixture file.
 */
public final class CrossReceiverContractTest {

    private static int passed = 0;
    private static int failed = 0;
    private static final StringBuilder failures = new StringBuilder();

    private static void check(String name, boolean ok) { check(name, ok, ""); }

    private static void check(String name, boolean ok, String detail) {
        if (ok) {
            passed++;
            System.out.println("  ok   " + name);
        } else {
            failed++;
            failures.append("    - ").append(name).append('\n');
            System.out.println("  FAIL " + name + (detail.isEmpty() ? "" : "  " + detail));
        }
    }

    // ---- a very small JSON reader, so the test has no dependencies ----------------------------

    /** Pull the string values of a flat JSON array under "key". */
    private static List<String> stringArray(String json, String key) {
        List<String> out = new ArrayList<>();
        int i = json.indexOf("\"" + key + "\"");
        if (i < 0) { return out; }
        int open = json.indexOf('[', i);
        int close = json.indexOf(']', open);
        if (open < 0 || close < 0) { return out; }
        String body = json.substring(open + 1, close);
        int p = 0;
        while (true) {
            int a = body.indexOf('"', p);
            if (a < 0) { break; }
            int b = body.indexOf('"', a + 1);
            if (b < 0) { break; }
            out.add(body.substring(a + 1, b));
            p = b + 1;
        }
        return out;
    }

    /**
     * Read "token": "VERDICT" pairs out of the "classification" object.
     *
     * The scope matters: the token ALSO appears in the runtime_tokens array earlier in the file.
     * A naive indexOf(token) finds that array element and then reads whatever string follows it,
     * yielding a classification shifted by one position - which reads as a real vocabulary
     * disagreement and is actually a broken reader. So: isolate the classification object FIRST,
     * then search inside it.
     */
    private static String classificationOf(String json, String token) {
        int key = json.indexOf("\"classification\"");
        if (key < 0) { return null; }
        int open = json.indexOf('{', key);
        if (open < 0) { return null; }
        // find the matching close brace for this object
        int depth = 0;
        int close = -1;
        for (int i = open; i < json.length(); i++) {
            char c = json.charAt(i);
            if (c == '{') { depth++; }
            else if (c == '}') { depth--; if (depth == 0) { close = i; break; } }
        }
        if (close < 0) { return null; }
        String scope = json.substring(open, close);

        int i = scope.indexOf("\"" + token + "\"");
        if (i < 0) { return null; }
        int c2 = scope.indexOf(':', i);
        int a = scope.indexOf('"', c2);
        int b = scope.indexOf('"', a + 1);
        if (c2 < 0 || a < 0 || b < 0) { return null; }
        return scope.substring(a + 1, b);
    }

    private static String readFile(File f) throws Exception {
        return new String(Files.readAllBytes(f.toPath()), StandardCharsets.UTF_8);
    }

    // ---- the schema_version / provenance rules, mirrored from the contract ---------------------

    /**
     * The contract: `schema_version` is optional; ABSENT means legacy v0 and is accepted+counted;
     * the canonical value is 1; ANY OTHER PRESENT VALUE is refused.
     *
     * 0 is the interesting case and the one worth pinning: it is a PRESENT value, so it is not
     * "absent/legacy", and it is not 1, so it must be refused. Treating 0 as "absent" would quietly
     * accept a malformed producer.
     */
    static String schemaVersionVerdict(Integer version, boolean strictMode) {
        if (version == null) {
            return strictMode ? "REFUSE_missing_schema_version" : "ACCEPT_legacy_v0";
        }
        if (version.intValue() == 1) {
            return "ACCEPT";
        }
        return "REFUSE_unsupported_schema_version";
    }

    /**
     * The contract: a producer's provenance is a CLAIM. A claim may never widen, absence is never
     * real, and an unknown claim string is refused.
     */
    static String provenanceVerdict(String claim, boolean sessionIsSynthetic) {
        if (claim == null) {
            return "RECORD_synthetic";            // absence must never travel as a real claim
        }
        if ("synthetic".equals(claim)) {
            return "RECORD_synthetic";            // a claim may not deflate the hub either
        }
        if ("real".equals(claim) || "real_device".equals(claim)) {
            return sessionIsSynthetic ? "REFUSE_provenance_claim_widens_session" : "RECORD_real";
        }
        return "REFUSE_unknown_provenance_claim";
    }

    public static void main(String[] args) throws Exception {
        System.out.println("== cross-receiver contract: producer -> transport -> receiver ==");

        String root = System.getProperty("hg.root");
        if (root == null) {
            System.out.println("  SKIP  hg.root not set - cannot locate the fixture");
            return;
        }
        File fx = new File(root, "hg_verify/cross_receiver_fixture.json");
        if (!fx.isFile()) {
            System.out.println("  SKIP  fixture absent: " + fx.getPath()
                    + " (run scripts/gen_cross_receiver_fixture.py)");
            return;
        }

        String json = readFile(fx);
        List<String> runtime = stringArray(json, "runtime_tokens");
        check("X0 the fixture is non-empty and carries the receiver vocabulary",
                runtime.size() > 10, "tokens=" + runtime.size());

        // ---- X1: the two vocabularies are the same --------------------------------------------
        List<String> androidAll = new ArrayList<>();
        androidAll.addAll(stringArray(json, "PERMANENT"));
        androidAll.addAll(stringArray(json, "SUSPENDING"));
        androidAll.addAll(stringArray(json, "RETRYABLE"));
        List<String> onlyAndroid = new ArrayList<>();
        for (String t : androidAll) { if (!runtime.contains(t)) { onlyAndroid.add(t); } }
        List<String> onlyReceiver = new ArrayList<>();
        for (String t : runtime) { if (!androidAll.contains(t)) { onlyReceiver.add(t); } }
        check("X1a every token the receiver can emit is known to the Android transport",
                onlyReceiver.isEmpty(),
                "receiver-only=" + onlyReceiver + " - these fall through to PERMANENT, so a "
                        + "condition that should SUSPEND would silently drop one observation");
        check("X1b every Android token is one the receiver can actually emit",
                onlyAndroid.isEmpty(), "android-only=" + onlyAndroid + " (dead rule: never fires)");

        // ---- X2: the fixture's classification matches production's ---------------------------------
        int mismatches = 0;
        StringBuilder detail = new StringBuilder();
        for (String t : runtime) {
            String fromFixture = classificationOf(json, t);
            String fromJava = ObservationTransport.classifyReason(t);
            if (fromFixture == null || !fromFixture.equals(fromJava)) {
                mismatches++;
                detail.append(t).append("(fixture=").append(fromFixture)
                      .append(",java=").append(fromJava).append(") ");
            }
        }
        check("X2 every runtime token is classified identically by the fixture and by production",
                mismatches == 0, detail.toString());

        // ---- X3/X4: SUSPEND actually stops, and stopping is not retrying -------------------------
        String[] mustSuspend = {"consent_withdrawn", "consent_missing", "capture_disabled",
                                "device_revoked", "device_unpaired", "device_unknown",
                                "identity_mismatch", "unauthorized"};
        for (String t : mustSuspend) {
            String v = ObservationTransport.classifyReason(t);
            check("X3 '" + t + "' is SUSPEND, not a retryable/permanent drop", "SUSPEND".equals(v),
                    "got " + v);
        }

        // A suspended transport must hold the queue instead of retrying: the loop checks `suspended`
        // before transmitting, so the observation is never sent again while suspended. Model that and
        // require zero additional transmits.
        int transmitsWhileSuspended = transmitsWhileSuspended("device_revoked", 50);
        check("X4a a revoked device produces ZERO further transmit attempts (stopped, not retried)",
                transmitsWhileSuspended == 0, "attempts=" + transmitsWhileSuspended);
        // Negative control for X4a: if the reason were classified RETRY, the loop WOULD transmit.
        int transmitsIfRetryable = transmitsWhileSuspended("queue_full", 50);
        check("X4b negative control: the same loop with a RETRYABLE reason does transmit "
                        + "(so X4a is measuring the disposition, not a broken loop)",
                transmitsIfRetryable > 0, "attempts=" + transmitsIfRetryable);

        // ---- X5: unknown fails closed ---------------------------------------------------------
        check("X5a an unrecognised reason is PERMANENT (fail closed)",
                "PERMANENT".equals(ObservationTransport.classifyReason("some_future_reason")));
        check("X5b a null reason is PERMANENT rather than throwing",
                "PERMANENT".equals(ObservationTransport.classifyReason(null)));
        check("X5c the receiver's own fail-closed default is a real token this side understands",
                runtime.contains("unauthorized")
                        && "SUSPEND".equals(ObservationTransport.classifyReason("unauthorized")));

        // ---- X6: replay is not retried ----------------------------------------------------------
        check("X6 a replayed sequence is PERMANENT: resending the same sequence cannot fix it",
                "PERMANENT".equals(ObservationTransport.classifyReason("replayed_sequence")));

        // ---- X7: schema_version, including 0 ------------------------------------------------------
        check("X7a schema_version 1 is accepted",
                "ACCEPT".equals(schemaVersionVerdict(1, false)));
        check("X7b absent schema_version is legacy v0 and accepted while strict mode is off",
                "ACCEPT_legacy_v0".equals(schemaVersionVerdict(null, false)));
        check("X7c absent schema_version is refused when strict mode is on",
                "REFUSE_missing_schema_version".equals(schemaVersionVerdict(null, true)));
        check("X7d schema_version 0 is REFUSED - it is a PRESENT value, not 'absent/legacy'",
                "REFUSE_unsupported_schema_version".equals(schemaVersionVerdict(0, false)),
                "got " + schemaVersionVerdict(0, false));
        check("X7e schema_version 2 is refused",
                "REFUSE_unsupported_schema_version".equals(schemaVersionVerdict(2, true)));
        check("X7f negative control: 0 and null must NOT share a verdict",
                !schemaVersionVerdict(0, false).equals(schemaVersionVerdict(null, false)));

        // ---- X8: provenance may never be elevated -------------------------------------------------
        check("X8a a claim of real origin on a synthetic session is REFUSED, not downgraded quietly",
                "REFUSE_provenance_claim_widens_session".equals(
                        provenanceVerdict("real_device", true)));
        check("X8b absence records synthetic - it never travels as a real claim",
                "RECORD_synthetic".equals(provenanceVerdict(null, false)));
        check("X8c a synthetic claim on a synthetic session records synthetic",
                "RECORD_synthetic".equals(provenanceVerdict("synthetic", true)));
        check("X8d a synthetic claim cannot deflate a real session",
                "RECORD_synthetic".equals(provenanceVerdict("synthetic", false)));
        check("X8e an unknown claim string is refused",
                "REFUSE_unknown_provenance_claim".equals(provenanceVerdict("probably_real", true)));

        // Fixture data must never be labelled as real camera evidence: the default the producer uses
        // for generated fixtures must be the non-claiming value.
        check("X8f generated fixture data is never labelled 'real' by default",
                "RECORD_synthetic".equals(provenanceVerdict(null, true))
                        && !"RECORD_real".equals(provenanceVerdict(null, true)));

        // ---- X9: negative control ----------------------------------------------------------------
        // The X1 comparison must be able to fail. Feed it a deliberately invented token and require
        // the same comparison to report a mismatch.
        List<String> poisoned = new ArrayList<>(runtime);
        poisoned.add("definitely_not_a_receiver_token");
        boolean detected = false;
        for (String t : poisoned) { if (!androidAll.contains(t)) { detected = true; break; } }
        check("X9 negative control: an invented receiver token is detected as unknown",
                detected, "if this is false, X1a proves nothing");

        // ---- D: D-03 RECEIVER INGRESS BOUNDS ------------------------------------------------------
        // Read from the real receiver (src/net/DeviceProtocol.h/.cpp @ 02ab07c), not from a scripted
        // peer. Emitting outside these does not fail locally - it fails at the hub as a remote
        // `bad_json` that names no field. These cases assert the producer is inside the bounds, and
        // that a bad identity is refused LOCALLY.
        check("D1 device_id bound matches the receiver (96)",
                ObservationTransport.MAX_DEVICE_ID_CHARS == 96);
        check("D2 display_name bound matches the receiver (64)",
                ObservationTransport.MAX_DISPLAY_NAME_CHARS == 64);
        check("D3 capability entry bound matches the receiver (32)",
                ObservationTransport.MAX_CAPABILITY_CHARS == 32);
        check("D4 capabilities count bound matches the receiver (16), and 2 are emitted",
                ObservationTransport.MAX_CAPABILITIES == 16);
        check("D5 feature string bound matches the receiver (64)",
                ObservationTransport.MAX_FEATURE_STRING_CHARS == 64);
        check("D6 feature key bound matches the receiver (24), and 2 keys are emitted",
                ObservationTransport.MAX_FEATURE_KEYS == 24);
        check("D7 sequence ceiling matches the receiver (1<<60)",
                ObservationTransport.MAX_SEQUENCE == (1L << 60));
        check("D8 future-skew window matches the receiver (120000 ms)",
                ObservationTransport.MAX_FUTURE_SKEW_MS == 120000L);
        check("D9 observation age window matches the receiver (86400000 ms)",
                ObservationTransport.MAX_OBSERVATION_AGE_MS == 86400000L);

        // The identity the producer actually emits must be acceptable.
        ObservationTransport.Config goodCfg = new ObservationTransport.Config();
        goodCfg.deviceId = "hg-android-test-device";
        goodCfg.displayName = "test node";
        check("D10 a normal identity is accepted locally",
                ObservationTransport.identityRejection(goodCfg) == null,
                "got " + ObservationTransport.identityRejection(goodCfg));

        ObservationTransport.Config longId = new ObservationTransport.Config();
        longId.deviceId = new String(new char[97]).replace('\0', 'x');
        check("D11 a device_id one char over the bound is refused LOCALLY, not at the hub",
                ObservationTransport.identityRejection(longId) != null,
                "an over-long id must fail here where it can be named");

        ObservationTransport.Config emptyId = new ObservationTransport.Config();
        emptyId.deviceId = "";
        check("D12 an empty device_id is refused locally",
                ObservationTransport.identityRejection(emptyId) != null);

        // The clock window, which is the field failure that looks like a transport fault.
        long now = System.currentTimeMillis();
        ObservationTransport.PendingObservation okObs =
                new ObservationTransport.PendingObservation("obs-1", "camera", "motion", "synthetic",
                        now, 1L, 0.5d, "fraction", "present", 0.9d, "synthetic");
        check("D13 a normal observation is accepted locally",
                ObservationTransport.observationRejection(okObs, now) == null,
                "got " + ObservationTransport.observationRejection(okObs, now));

        ObservationTransport.PendingObservation skewed =
                new ObservationTransport.PendingObservation("obs-2", "camera", "motion", "synthetic",
                        now + 300000L, 2L, 0.5d, "fraction", "present", 0.9d, "synthetic");
        check("D14 an observation timestamped 5 min in the future is refused locally as clock skew",
                ObservationTransport.observationRejection(skewed, now) != null,
                "a skewed phone clock would otherwise be refused remotely as malformed_timestamp");

        ObservationTransport.PendingObservation ancient =
                new ObservationTransport.PendingObservation("obs-3", "camera", "motion", "synthetic",
                        now - 90000000L, 3L, 0.5d, "fraction", "present", 0.9d, "synthetic");
        check("D15 an observation older than 24 h is refused locally",
                ObservationTransport.observationRejection(ancient, now) != null);

        ObservationTransport.PendingObservation zeroSeq =
                new ObservationTransport.PendingObservation("obs-4", "camera", "motion", "synthetic",
                        now, 0L, 0.5d, "fraction", "present", 0.9d, "synthetic");
        check("D16 sequence 0 is refused locally (the receiver rejects value == 0)",
                ObservationTransport.observationRejection(zeroSeq, now) != null);

        // ---- H: the handshake, which had NO coverage before this --------------------------------
        // `expectWelcome` takes an SSLSocket, so nothing could drive it. That is the worst place to
        // have a gap: the welcome carries the resume watermark, the one field a restarted node needs
        // in order not to replay from 1 and be refused as a replay on every line.
        final int MAJOR = ObservationTransport.protocolVersionMajor();
        String ok = "{\"kind\":\"welcome\",\"protocol_version_major\":" + MAJOR
                + ",\"protocol_version_minor\":0,\"last_sequence\":41}";

        check("H1 a well-formed welcome is ACCEPT",
                ObservationTransport.WELCOME_OK.equals(ObservationTransport.welcomeVerdict(ok)),
                "got " + ObservationTransport.welcomeVerdict(ok));
        check("H2 no frame at all is refused, not treated as an empty welcome",
                "REJECT_no_frame".equals(ObservationTransport.welcomeVerdict(null)));
        check("H3 an unparseable frame is refused rather than throwing",
                "REJECT_unreadable".equals(ObservationTransport.welcomeVerdict("{not json")));
        check("H4 a non-welcome kind is refused",
                "REJECT_not_welcome".equals(
                        ObservationTransport.welcomeVerdict("{\"kind\":\"ack\"}")));
        check("H5 a welcome with the WRONG MAJOR VERSION is refused",
                "REJECT_version".equals(ObservationTransport.welcomeVerdict(
                        "{\"kind\":\"welcome\",\"protocol_version_major\":" + (MAJOR + 1) + "}")),
                "this is the defect this section was added for: the ack path checked the version and "
                        + "the welcome path did not");
        check("H6 a welcome with NO version field is refused (fails closed, not defaulted)",
                "REJECT_version".equals(
                        ObservationTransport.welcomeVerdict("{\"kind\":\"welcome\"}")));

        // The watermark, and the regression it prevents.
        check("H7 the resume watermark is read from the wire name the receiver actually sends",
                ObservationTransport.resumeWatermark(ok) == 41L,
                "got " + ObservationTransport.resumeWatermark(ok));
        check("H8 a schema-named 'resume_after_sequence' is NOT the wire field (doc drift, asserted)",
                ObservationTransport.resumeWatermark(
                        "{\"kind\":\"welcome\",\"resume_after_sequence\":99}") == 0L,
                "the receiver serialises out[\"last_sequence\"]; the schema calls it "
                        + "resume_after_sequence, which is the C++ struct field name");
        check("H9 a watermark advances the counter",
                ObservationTransport.adoptedSequence(0L, 41L) == 41L);
        check("H10 a watermark never rewinds the counter",
                ObservationTransport.adoptedSequence(100L, 5L) == 100L);
        check("H11 an absent watermark leaves the counter alone",
                ObservationTransport.adoptedSequence(7L, 0L) == 7L);
        check("H12 negative control: resuming from 1 after a watermark would be a replay",
                ObservationTransport.adoptedSequence(0L, 41L) != 0L,
                "if this were 0 the node would restart at 1 and every line would be replays");

        System.out.println();
        if (failed > 0) {
            System.out.println("  FAILED: " + failed + " of " + (passed + failed));
            System.out.print(failures);
            System.exit(1);
        }
        System.out.println("  PASS: all " + passed + " cross-receiver contract cases behave as specified");
    }

    /**
     * Model the transport loop: a SUSPENDED transport checks `suspended` BEFORE transmitting and
     * holds the queue, so it makes no further attempts; any other disposition keeps the loop running.
     * The count is the number of transmit attempts for one observation given that reason.
     */
    static int transmitsWhileSuspended(String reason, int maxTicks) {
        String verdict = ObservationTransport.classifyReason(reason);
        if ("SUSPEND".equals(verdict)) {
            // The loop sees suspended and sleeps; it never reaches transmit().
            return 0;
        }
        int attempts = 0;
        for (int i = 0; i < maxTicks; i++) {
            attempts++;
            if ("PERMANENT".equals(verdict)) {
                return attempts;              // dropped on the first attempt
            }
            if (attempts >= ObservationTransport.maxAttemptsPerObservation()) {
                return attempts;              // dropped at the bound
            }
        }
        return attempts;
    }
}
